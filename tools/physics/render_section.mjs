#!/usr/bin/env node
/**
 * 把 assets/physics-data.json 渲染进 notes.html 的占位标记之间。
 *
 * 第一性原理
 * ----------
 * 读者不需要 JavaScript 才能看见公式。所以 KaTeX 只在**构建期**运行，
 * 产物是纯 HTML + CSS + woff2 字体；页面运行时零 JS、零外部请求。
 * 渲染失败必须让构建失败（throwOnError），不能悄悄降级成一段红字。
 *
 * 用法
 * ----
 *   node tools/physics/render_section.mjs          # 渲染并写回 notes.html
 *   node tools/physics/render_section.mjs --check  # 只校验 HTML 是否与数据同步
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import katex from "katex";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const DATA = path.join(ROOT, "assets/physics-data.json");
const PAGE = path.join(ROOT, "notes.html");

const KATEX = {
  throwOnError: true,
  strict: false,
  trust: false,
  output: "html",
};

const tex = (s) => katex.renderToString(s, { ...KATEX, displayMode: false });
const texBlock = (s) => katex.renderToString(s, { ...KATEX, displayMode: true });

/** 数值格式：7 位有效数字，去掉浮点尾巴；极端量级转上标科学计数。 */
const SUP = { "-": "⁻", 0: "⁰", 1: "¹", 2: "²", 3: "³", 4: "⁴", 5: "⁵", 6: "⁶", 7: "⁷", 8: "⁸", 9: "⁹" };
const sup = (n) => String(n).split("").map((ch) => SUP[ch] ?? ch).join("");

function fmt(v) {
  if (!Number.isFinite(v)) return String(v);
  const a = Math.abs(v);
  if (a === 0) return "0";
  if (a >= 1e-3 && a < 1e6) return String(parseFloat(v.toPrecision(7)));
  const [m, e] = v.toExponential(4).split("e");
  return `${parseFloat(m)}×10${sup(Number(e))}`;
}

/** 每个条目的符号标签与单位（展示用，与 JSON 中的数值一一对应）。 */
const DISPLAY = {
  "lf-energy": {
    rows: [{ key: "k^{+}k^{-}", value: "1.75", unit: "GeV²" }],
    note: "on-shell point: k⁰ = 2, k³ = 3/2, m = 1/2, k⊥ = √(3/2), all in GeV",
  },
  "fock-normalisation": {
    rows: [
      { key: "\\int x_{1}x_{2}x_{3}\\,\\mathrm{d}\\Sigma", value: "1/120", unit: "dimensionless" },
      { key: "\\mathcal{N}=\\sqrt{120}", value: "10.95445", unit: "dimensionless" },
    ],
    note: "model wave function Ψ ∝ x₁x₂x₃; normalisation fixed by P₃q = 1",
  },
  "dis-kinematics": {
    rows: [
      { key: "Q^{2}", value: null, unit: "GeV²" },
      { key: "x_{B}", value: null, unit: "" },
      { key: "y", value: null, unit: "" },
      { key: "s", value: null, unit: "GeV²" },
      { key: "W", value: null, unit: "GeV" },
    ],
    note: "HERA beams: E_e = 27.6 GeV, E_p = 920 GeV, E′_e = 10 GeV, θ = 150°",
  },
};

const VALUES_FOR = {
  "dis-kinematics": ["Q2", "x_B", "y", "s", "W"],
};

function renderClaim(claim, provenance) {
  const prov =
    `generated by ${provenance.generator} · sympy ${provenance.sympy} · ` +
    `data sha ${provenance.contentHash}`;
  const disp = DISPLAY[claim.id];
  if (!disp) throw new Error(`no display mapping for claim ${claim.id}`);

  const vals = claim.numeric.values || {};
  const keys = VALUES_FOR[claim.id] || [];

  const rows = disp.rows
    .map((row, i) => {
      const jsonKey = keys[i];
      const value = jsonKey === undefined ? row.value : fmt(vals[jsonKey]);
      return [
        `        <div class="eq-row">`,
        `          <span class="eq-k">${tex(row.key)}</span>`,
        `          <span class="eq-v">${value}</span>`,
        `          <span class="eq-u">${row.unit}</span>`,
        `        </div>`,
      ].join("\n");
    })
    .join("\n");

  const checks = claim.checks
    .map(
      (c) =>
        `        <li class="${c.status}">${escapeHtml(c.en || c.detail)}</li>`,
    )
    .join("\n");

  const failed = claim.checks.filter((c) => c.status !== "pass").length;

  return [
    `<figure class="eq" id="eq-${claim.id}" data-checks="${claim.checks.length}" data-failed="${failed}">`,
    `  <span class="eq-tag">${claim.label} · SYMBOLIC + NUMERIC</span>`,
    `      <div class="eq-formula">${texBlock(claim.formula.latex)}</div>`,
    `      <div class="eq-rows">`,
    rows,
    `      </div>`,
    `      <p class="eq-note">${escapeHtml(disp.note)}</p>`,
    `      <ul class="eq-checks">`,
    checks,
    `      </ul>`,
    `      <p class="eq-src">${escapeHtml(prov)}</p>`,
    `    </figure>`,
  ].join("\n");
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function render(data, page) {
  // 跟随文件自身的换行风格：编辑器或脚本可能把整份文件规范化成 CRLF，
  // 硬编码 LF 会让 --check 把「换行符不同」误报成「内容过期」。
  const LF = String.fromCharCode(10);
  const CRLF = String.fromCharCode(13, 10);
  const EOL = page.includes(CRLF) ? CRLF : LF;
  let out = page;
  for (const claim of data.claims) {
    const open = `<!-- phys:${claim.id} -->`;
    const close = `<!-- /phys:${claim.id} -->`;
    const start = out.indexOf(open);
    const end = out.indexOf(close);
    if (start < 0 || end < 0 || end < start) {
      throw new Error(`markers missing or misordered for ${claim.id}`);
    }
    const block = renderClaim(claim, {
      generator: data.provenance.generator,
      sympy: data.provenance.sympy,
      contentHash: data.content_hash,
    }).split(LF).join(EOL);
    out =
      out.slice(0, start + open.length) +
      EOL + "      " + block + EOL + "      " +
      out.slice(end);
  }
  return out;
}

const check = process.argv.includes("--check");
const data = JSON.parse(fs.readFileSync(DATA, "utf8"));
const page = fs.readFileSync(PAGE, "utf8");

if (data.summary.failed > 0) {
  console.error(`refusing to render: ${data.summary.failed} failing checks in physics-data.json`);
  process.exit(1);
}

const rendered = render(data, page);

if (rendered.includes("katex-error")) {
  console.error("katex produced an error node — aborting");
  process.exit(1);
}

if (check) {
  if (rendered !== page) {
    console.error("notes.html is stale — rerun: node tools/physics/render_section.mjs");
    process.exit(1);
  }
  console.log(`phys-render: OK (${data.claims.length} blocks, hash ${data.content_hash})`);
  process.exit(0);
}

fs.writeFileSync(PAGE, rendered, "utf8");
const failed = data.claims.reduce((n, c) => n + c.checks.filter((k) => k.status !== "pass").length, 0);
console.log(
  `rendered ${data.claims.length} blocks into notes.html · checks ${failed === 0 ? "all pass" : failed + " FAILED"} · ` +
    `sympy ${data.provenance.sympy} · hash ${data.content_hash}`,
);
